import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root='dist/client';
const files=fs.readdirSync(root,{recursive:true}).filter(f=>f.endsWith('.js'));
const page=files.map(f=>fs.readFileSync(path.join(root,f),'utf8')).find(s=>s.includes('new Worker('));
assert.ok(page,'Client worker constructor exists');
assert.ok(!/new Worker\(new URL\([^)]*file:/.test(page),'Worker must not resolve against a file:// build address');
const asset=page.match(/\/_next\/static\/lap\.worker-[\w-]+\.js/)?.[0];
assert.ok(asset,'Client contains a same-origin worker asset URL');
assert.equal(new URL(asset,'https://example.test').origin,'https://example.test');
const code=fs.readFileSync(path.join(root,asset),'utf8');
const replies=[];const self={postMessage:message=>replies.push(message)};
vm.runInNewContext(code,{self,Math},{timeout:2000});
const setup={frontWing:18,rearWing:22,rideHeight:35,fuel:25,ballast:0,power:600,tire:'medium',brakeBias:56,camber:-2.5,toe:.1};
self.onmessage({data:{id:1,setup}});
assert.equal(replies[0].id,1);assert.ok(!replies[0].error);assert.ok(replies[0].lap.lapTime>0);assert.equal(replies[0].lap.lapTime,replies[0].baseline.lapTime);
self.onmessage({data:{id:2,setup:{...setup,power:350}}});
assert.ok(replies[1].lap.lapTime>replies[0].lap.lapTime);
assert.ok(replies[0].lap.suspension.samples.length===replies[0].lap.path.length);
assert.ok(replies[1].lap.suspension.samples.every(s=>Number.isFinite(s.rollDeg)&&s.fl>=0));
self.onmessage({data:{id:3,vehicleId:'sf26',setup}});
assert.ok(replies[2].error);assert.equal(replies[2].lap,undefined);
const sf={frontWing:0,rearWing:0,rideHeight:35,fuel:25,ballast:0,power:380,tire:'medium',brakeBias:56,camber:0,toe:0,finalDrive:4.1,frontWeight:46,cgHeight:300,frontSpring:0,rearSpring:0,frontARB:0,rearARB:0,tirePressure:0,gripScale:1,brakeLimit:5,gear1:3.1,gear2:2.55,gear3:2.12,gear4:1.81,gear5:1.58,gear6:1.4,gear7:1.26,gear8:1.14,dryMass:770,frontClA:2,rearClA:2.6,baseCdA:1};
self.onmessage({data:{id:4,vehicleId:'sf26',setup:sf}});assert.ok(!replies[3].error,replies[3].error);assert.equal(replies[3].lap.vehicleId,'sf26');assert.equal(replies[3].lap.suspension,undefined);assert.ok(replies[3].lap.lapTime>0);
self.onmessage({data:{id:5,vehicleId:'sf26',setup:{...sf,power:250}}});assert.ok(replies[4].lap.lapTime>replies[3].lap.lapTime);
self.onmessage({data:{id:6,vehicleId:'sf26',setup:sf,trajectory:{version:1,id:'custom',name:'Worker custom',offsets:Array.from({length:24},(_,i)=>Math.sin(i)*2)}}});assert.ok(!replies[5].error);assert.ok(replies[5].lap.telemetry.some(t=>Math.abs(t.offset)>.5));
console.log('SF-26 production worker: separate model, input rejection, power sensitivity and custom trajectory passed.');
console.log('Production worker verified: same-origin URL, packaged asset exists, baseline and modified runs return valid results.');
